// Regenerate server/track.mjs from the coast control points in src/world.ts.
// The API uses this polyline to reject grass-cutting and teleports, so run it
// whenever the circuit changes: npm run track
import * as THREE from 'three';
import fs from 'node:fs';

const src = fs.readFileSync(new URL('../src/world.ts', import.meta.url), 'utf8');
const block = src.match(/id:\s*'coast'[^]*?ctrl:\s*\[([\s\S]*?)\],\s*\n\s*palette/)[1];
if (!block) throw new Error('coast ctrl block not found');
const ctrl = [...block.matchAll(/\[\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\]/g)]
  .map((m) => [Number(m[1]), Number(m[2])]);
const curve = new THREE.CatmullRomCurve3(
  ctrl.map(([x, z]) => new THREE.Vector3(x, 0, z)), true, 'catmullrom', 0.5,
);
const pts = curve.getPoints(900);
const out = [];
for (let i = 0; i < pts.length; i += 2) {
  out.push(Math.round(pts[i].x * 100) / 100, Math.round(pts[i].z * 100) / 100);
}
const n = out.length / 2;
const start = Math.floor(Math.floor(pts.length / 3) / 2);
const body = `// Generated by scripts/gen-track.mjs from the coast control points in
// src/world.ts (every 2nd sample of CatmullRomCurve3.getPoints(900), ~0.8-unit
// spacing). Run \`npm run track\` after changing the circuit.
export const TRACK_HALF = 4.4;
export const TRACK_START = ${start};
export const TRACK_POINTS = [
${Array.from({ length: n }, (_, i) => `  ${out[i * 2]}, ${out[i * 2 + 1]},`).join('\n')}
];

const N = TRACK_POINTS.length / 2;

/** squared distance from (x,z) to the nearest sampled centreline point */
export function nearestTrack(x, z) {
  let best = Infinity, at = 0;
  for (let i = 0; i < N; i++) {
    const dx = TRACK_POINTS[i * 2] - x;
    const dz = TRACK_POINTS[i * 2 + 1] - z;
    const d = dx * dx + dz * dz;
    if (d < best) { best = d; at = i; }
  }
  return { d: Math.sqrt(best), i: at };
}

export function distanceToTrack(x, z) {
  return nearestTrack(x, z).d;
}

/** lap progress 0..1 relative to the start line, rounded to sample resolution */
export function trackU(x, z) {
  const { i } = nearestTrack(x, z);
  return ((i - TRACK_START + N) % N) / N;
}
`;
fs.writeFileSync(new URL('../server/track.mjs', import.meta.url), body);
console.log(`wrote server/track.mjs: ${n} points, start ${start}`);
